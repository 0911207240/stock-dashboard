"""各 ETF 配息來源的查證結果（定期定額頁與配置模擬共用）

非股利占比＝1 − 54C 股利所得% − 5A 利息所得%，以近 12 個月每期配息金額加權。
剩下的部分多為已實現資本利得，也可能含收益平準金；各期細項拆分只有最新一期公開，
所以這是上限估計。來源：ETF 資訊網各檔配息紀錄頁（整理自投信公告），2026/10/17 讀取；
其中 00878、00919、00929 最近一期與官方資料互相吻合。數字會過期，需定期重查。
"""

NONDIV_ASOF = "2026/10/17"
NONDIV_DEFAULT = 0.50  # 未查證的標的先假設一半

NONDIV = {"0050": 0.70, "0056": 0.67, "00878": 0.72, "00919": 0.84, "00929": 0.67,
          "00940": 0.17, "00900": 0.36, "00939": 0.28}


def nondiv(code: str) -> float:
    return NONDIV.get(code, NONDIV_DEFAULT)


def nondiv_label(code: str) -> str:
    """表格用：已查證顯示百分比，未查證加「約」並標註"""
    return f"{NONDIV[code] * 100:.0f}%" if code in NONDIV else f"約{NONDIV_DEFAULT * 100:.0f}%（未查證）"
